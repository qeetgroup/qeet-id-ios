#!/usr/bin/env python3
"""Generates the launch screen's images (QeetID/Resources/LaunchScreen.storyboard): LaunchMark, the 112 pt app icon,
and LaunchBranding, "from" over "Qeet Group", light and dark, in QeetID/Resources/Assets.xcassets.

The Launch mockup (qeet-mockups, products/qeet-id, 01 Launch) draws the icon at 112 pt in the middle on iOS, and at the
foot, 48 pt above the safe area, "from" in body.sm (12/16) in color.text.subtle over "Qeet Group" in body.lg (16/24) at
weight 600 in color.text.default, space.gap.xs apart. A launch screen can't load the app's fonts, so the words are Qeet
Sans's own glyph outlines, shaped by HarfBuzz at the axes Qeetrix uses (opsz = the size, GEOM = font.geometry.body,
wght), each line centred and its baseline where CSS puts it in its line box. The icon is the brand's geometry in a
100-unit box, as Components/Brand.swift and Scripts/render-app-icon.swift draw it.

    python3 -m venv .venv && .venv/bin/pip install fonttools uharfbuzz
    .venv/bin/python Scripts/generate-launch-screen.py [path to QeetSans.ttf]

The font defaults to Qeetrix for iOS's copy in Xcode's package checkout (DerivedData). Run it again when the words, the
type, the colours or the icon change.
"""

import glob
import json
import pathlib
import sys

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "QeetID/Resources/Assets.xcassets"
CHECKOUTS = "~/Library/Developer/Xcode/DerivedData/QeetID-*/SourcePackages/checkouts"
FONT_IN_PACKAGE = "qeetrix-ios/Sources/Qeetrix/Resources/Fonts/QeetSans.ttf"

# The icon's size on the launch screen, in points.
MARK = 112
# The words' box: wide enough for "Qeet Group", as tall as the two lines and the gap between them.
BOX_WIDTH = 160
# space.gap.xs between the two lines.
GAP = 4
# font.geometry.body: the GEOM axis for body text.
GEOM_BODY = 0

# (text, size, line height, weight, light colour, dark colour)
LINES = [
    # body.sm, color.text.subtle
    ("from", 12, 16, 400, "#484747", "#D1CFCE"),
    # body.lg at weight 600, color.text.default
    ("Qeet Group", 16, 24, 600, "#0E0D0D", "#F3F1EF"),
]
BOX_HEIGHT = sum(line[2] for line in LINES) + GAP * (len(LINES) - 1)


def number(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def line_paths(font_path, font_bytes, text, size, line_top, line_height, weight):
    """The line's glyph outlines as SVG path data, centred in the box, the baseline where CSS puts it."""
    axes = {"wght": weight, "opsz": size, "GEOM": GEOM_BODY}
    # Shape at the axes, so advances and kerning are the instance's.
    shaper = hb.Font(hb.Face(font_bytes))
    shaper.set_variations(axes)
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(shaper, buffer, {"kern": True, "liga": True})

    instance = instantiateVariableFont(TTFont(font_path), axes, updateFontNames=False)
    upm = instance["head"].unitsPerEm
    ascent, descent = instance["hhea"].ascent, instance["hhea"].descent
    scale = size / upm
    # CSS: the content area (ascent + descent) sits in the middle of the line box; the baseline is ascent below its top.
    content = (ascent - descent) * scale
    baseline = line_top + (line_height - content) / 2 + ascent * scale

    width = sum(position.x_advance for position in buffer.glyph_positions) * scale
    x = (BOX_WIDTH - width) / 2
    glyph_set = instance.getGlyphSet()
    order = instance.getGlyphOrder()
    paths = []
    pen_x = 0
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        origin_x = x + (pen_x + position.x_offset) * scale
        origin_y = baseline - position.y_offset * scale
        pen = SVGPathPen(glyph_set, ntos=number)
        glyph_set[order[info.codepoint]].draw(TransformPen(pen, (scale, 0, 0, -scale, origin_x, origin_y)))
        if pen.getCommands():
            paths.append(pen.getCommands())
        pen_x += position.x_advance
    return paths


def branding_svg(lines_paths, colours, theme):
    body = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{BOX_WIDTH}" height="{BOX_HEIGHT}" '
        f'viewBox="0 0 {BOX_WIDTH} {BOX_HEIGHT}">',
        f'<!-- Generated by Scripts/generate-launch-screen.py from Qeet Sans. Do not edit. "from Qeet Group", {theme}. -->',
    ]
    for paths, colour in zip(lines_paths, colours):
        body += [f'<path fill="{colour}" d="{path}"/>' for path in paths]
    body.append("</svg>")
    return "\n".join(body) + "\n"


def mark_svg():
    """The app icon as Components/Brand.swift draws it: the white keyhole disc on the Qeet orange gradient
    (#DA653A → #D04800 → #9B3314, from (0.2, 0) to (0.8, 1)) in the rounded square, corners 22.5 of 100."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{MARK}" height="{MARK}" viewBox="0 0 100 100">
<!-- Generated by Scripts/generate-launch-screen.py from the brand's geometry. Do not edit. -->
<defs><linearGradient id="orange" gradientUnits="userSpaceOnUse" x1="20" y1="0" x2="80" y2="100">
<stop offset="0" stop-color="#DA653A"/><stop offset="0.45" stop-color="#D04800"/><stop offset="1" stop-color="#9B3314"/>
</linearGradient></defs>
<rect width="100" height="100" rx="22.5" fill="url(#orange)"/>
<path fill="#FFFFFF" fill-rule="evenodd" d="M21 50a29 29 0 1 0 58 0a29 29 0 1 0-58 0ZM46.2 50.6L43.5 64.5H56.5L53.8 50.6A8.5 8.5 0 1 0 46.2 50.6Z"/>
</svg>
"""


def write_imageset(name, files):
    """An image set of single-scale vectors, which Xcode renders at each scale when it builds the app."""
    folder = ASSETS / f"{name}.imageset"
    folder.mkdir(exist_ok=True)
    images = []
    for filename, content, dark in files:
        (folder / filename).write_text(content)
        image = {"filename": filename, "idiom": "universal"}
        if dark:
            image = {"appearances": [{"appearance": "luminosity", "value": "dark"}], **image}
        images.append(image)
    contents = {"images": images, "info": {"author": "xcode", "version": 1}}
    (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")
    print(f"wrote {folder.relative_to(ROOT)}")


def main():
    if len(sys.argv) > 1:
        font = pathlib.Path(sys.argv[1])
    else:
        found = sorted(glob.glob(str(pathlib.Path(CHECKOUTS).expanduser() / FONT_IN_PACKAGE)))
        if not found:
            sys.exit("Qeet Sans not found: build the app once in Xcode, or pass the path to QeetSans.ttf.")
        font = pathlib.Path(found[-1])
    font_bytes = font.read_bytes()
    paths = []
    top = 0
    for text, size, line_height, weight, _, _ in LINES:
        paths.append(line_paths(font, font_bytes, text, size, top, line_height, weight))
        top += line_height + GAP
    write_imageset("LaunchMark", [("launch-mark.svg", mark_svg(), False)])
    write_imageset(
        "LaunchBranding",
        [
            ("launch-branding.svg", branding_svg(paths, [line[4] for line in LINES], "light"), False),
            ("launch-branding-dark.svg", branding_svg(paths, [line[5] for line in LINES], "dark"), True),
        ],
    )


if __name__ == "__main__":
    main()
